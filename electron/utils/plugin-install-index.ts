/**
 * Persist ClawX-managed plugin install records into OpenClaw's SQLite state
 * database (state/openclaw.sqlite).
 *
 * OpenClaw 2026.6+ reads trusted install metadata from SQLite at runtime,
 * not from transient plugins.installs in openclaw.json. OpenClaw 2026.10
 * stores the index as the `plugins.installedIndex` row of
 * `config_machine_state`; the older `installed_plugin_index` table is only
 * imported while migrating a pre-13 state schema and is dropped afterwards.
 */
import { existsSync, mkdirSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { logger } from './logger';

const INSTALLED_PLUGIN_INDEX_KEY = 'installed-plugin-index';
const INSTALLED_PLUGIN_INDEX_STATE_KEY = 'plugins.installedIndex';
const INSTALLED_PLUGIN_INDEX_WARNING = 'DO NOT EDIT. This file is generated by OpenClaw from plugin manifests, install records, and config policy. Use `openclaw plugins registry --refresh`, `openclaw plugins install/update/uninstall`, or `openclaw plugins enable/disable` instead.';
// OpenClaw imports `installed_plugin_index` only when user_version < 13.
const MACHINE_STATE_MIN_USER_VERSION = 13;
const PLUGIN_LIFECYCLE_LEASE = { scope: 'core:plugin-lifecycle', key: 'global' } as const;
const STATE_BUSY_TIMEOUT_MS = 5_000;

const INSTALLED_PLUGIN_INDEX_TABLE_SQL = `
CREATE TABLE IF NOT EXISTS installed_plugin_index (
  index_key TEXT NOT NULL PRIMARY KEY,
  version INTEGER NOT NULL,
  host_contract_version TEXT NOT NULL,
  compat_registry_version TEXT NOT NULL,
  migration_version INTEGER NOT NULL,
  policy_hash TEXT NOT NULL,
  generated_at_ms INTEGER NOT NULL,
  refresh_reason TEXT,
  install_records_json TEXT NOT NULL,
  plugins_json TEXT NOT NULL,
  diagnostics_json TEXT NOT NULL,
  warning TEXT,
  updated_at_ms INTEGER NOT NULL
);
`;

type InstallRecords = Record<string, Record<string, unknown>>;
/** Returns true when the records were changed and must be persisted. */
type InstallRecordsMutation = (records: InstallRecords) => boolean;

type MachineStateIndexRow = {
  revision: number;
  index: Record<string, unknown>;
};

function resolveOpenClawStateDir(): string {
  return process.env.OPENCLAW_STATE_DIR?.trim() || join(homedir(), '.openclaw');
}

function resolveOpenClawStateSqlitePath(): string {
  // OpenClaw 2026.7.1 moved the shared state database under state/.
  // Writing the legacy root-level database leaves Gateway migrations reading
  // stale plugin records from the canonical database.
  return join(resolveOpenClawStateDir(), 'state', 'openclaw.sqlite');
}

function isPlainRecord(value: unknown): value is Record<string, unknown> {
  return Boolean(value) && typeof value === 'object' && !Array.isArray(value);
}

function parseInstallRecords(raw: unknown): InstallRecords | null {
  const parsed = typeof raw === 'string'
    ? (() => {
      try {
        return JSON.parse(raw) as unknown;
      } catch {
        return null;
      }
    })()
    : raw;
  if (!isPlainRecord(parsed)) return null;
  const records: InstallRecords = {};
  for (const [pluginId, record] of Object.entries(parsed)) {
    if (isPlainRecord(record)) {
      records[pluginId] = record;
    }
  }
  return records;
}

function installRecordsMatch(
  left: Record<string, unknown>,
  right: Record<string, unknown>,
): boolean {
  const keys = ['source', 'spec', 'sourcePath', 'installPath', 'version', 'resolvedName', 'resolvedVersion', 'resolvedSpec'] as const;
  return keys.every((key) => left[key] === right[key]);
}

// OpenClaw re-validates these against the plugin's declared surface hash, so
// a widened plugin still requires fresh consent.
const CAPABILITY_ACCEPTANCE_KEYS = ['acceptedSurface', 'acceptedSurfaceHash', 'acceptedSurfaceAt', 'acceptedSurfaceIntegrity'] as const;

function upsertMutation(records: InstallRecords): InstallRecordsMutation {
  return (current) => {
    let changed = false;
    for (const [pluginId, record] of Object.entries(records)) {
      const existing = current[pluginId];
      if (existing && installRecordsMatch(existing, record)) continue;
      const acceptance = Object.fromEntries(
        CAPABILITY_ACCEPTANCE_KEYS.filter((key) => existing && Object.hasOwn(existing, key)).map((key) => [key, existing[key]]),
      );
      current[pluginId] = { ...record, ...acceptance };
      changed = true;
    }
    return changed;
  };
}

function removeMutation(pluginIds: string[]): InstallRecordsMutation {
  return (current) => {
    let changed = false;
    for (const pluginId of pluginIds) {
      if (Object.hasOwn(current, pluginId)) {
        delete current[pluginId];
        changed = true;
      }
    }
    return changed;
  };
}

function openStateDatabase(sqlitePath: string): DatabaseSync {
  const db = new DatabaseSync(sqlitePath);
  db.exec(`PRAGMA busy_timeout = ${STATE_BUSY_TIMEOUT_MS};`);
  return db;
}

function tableExists(db: DatabaseSync, tableName: string): boolean {
  return Boolean(db.prepare("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?").get(tableName));
}

function readUserVersion(db: DatabaseSync): number {
  const row = db.prepare('PRAGMA user_version').get() as { user_version?: number } | undefined;
  return typeof row?.user_version === 'number' ? row.user_version : 0;
}

function usesMachineStateIndex(db: DatabaseSync): boolean {
  return readUserVersion(db) >= MACHINE_STATE_MIN_USER_VERSION && tableExists(db, 'config_machine_state');
}

function hasActivePluginLifecycleLease(db: DatabaseSync, nowMs: number): boolean {
  if (!tableExists(db, 'state_leases')) return false;
  return Boolean(db.prepare(`
    SELECT 1
      FROM state_leases
     WHERE scope = ? AND lease_key = ? AND expires_at > ?
  `).get(PLUGIN_LIFECYCLE_LEASE.scope, PLUGIN_LIFECYCLE_LEASE.key, nowMs));
}

function readMachineStateIndex(db: DatabaseSync): MachineStateIndexRow | null | 'invalid' {
  const row = db.prepare('SELECT value_json FROM config_machine_state WHERE state_key = ?')
    .get(INSTALLED_PLUGIN_INDEX_STATE_KEY) as { value_json?: string } | undefined;
  if (!row) return null;
  try {
    const value = JSON.parse(String(row.value_json)) as unknown;
    if (
      !isPlainRecord(value)
      || typeof value.revision !== 'number'
      || !isPlainRecord(value.index)
      || parseInstallRecords(value.index.installRecords ?? {}) === null
    ) {
      return 'invalid';
    }
    return { revision: value.revision, index: value.index };
  } catch {
    return 'invalid';
  }
}

function createClawXManagedIndex(nowMs: number): Record<string, unknown> {
  // Same placeholder shape OpenClaw imports from a ClawX-written legacy row;
  // the placeholder versions make the next OpenClaw refresh rebuild plugins.
  return {
    version: 1,
    warning: INSTALLED_PLUGIN_INDEX_WARNING,
    hostContractVersion: 'clawx-managed',
    compatRegistryVersion: 'clawx-managed',
    migrationVersion: 1,
    policyHash: 'clawx-managed',
    generatedAtMs: nowMs,
    refreshReason: 'source-changed',
    installRecords: {},
    plugins: [],
    diagnostics: [],
  };
}

function withoutPluginProjections(plugins: unknown, pluginIds: Set<string>): unknown {
  if (!Array.isArray(plugins)) return plugins;
  return plugins.filter((plugin) => !(
    isPlainRecord(plugin)
    && (pluginIds.has(String(plugin.pluginId)) || pluginIds.has(String(plugin.installOwner)))
  ));
}

function mutateMachineStateIndex(
  db: DatabaseSync,
  sqlitePath: string,
  mutate: InstallRecordsMutation,
): boolean {
  db.exec('BEGIN IMMEDIATE;');
  let committed = false;
  try {
    const nowMs = Date.now();
    if (hasActivePluginLifecycleLease(db, nowMs)) {
      logger.warn(`[plugin] Skipped install metadata update in ${sqlitePath}: an OpenClaw plugin lifecycle operation holds the state lease`);
      return false;
    }

    const current = readMachineStateIndex(db);
    if (current === 'invalid') {
      logger.warn(`[plugin] Skipped install metadata update in ${sqlitePath}: the OpenClaw plugin index row is invalid; run OpenClaw Doctor to repair it`);
      return false;
    }

    const index = current?.index ?? createClawXManagedIndex(nowMs);
    const records = parseInstallRecords(index.installRecords ?? {}) ?? {};
    const before = new Map(Object.entries(records).map(([id, record]) => [id, JSON.stringify(record)]));
    if (!mutate(records)) {
      return false;
    }

    const changedIds = new Set([
      ...Object.keys(records).filter((id) => before.get(id) !== JSON.stringify(records[id])),
      ...[...before.keys()].filter((id) => !Object.hasOwn(records, id)),
    ]);
    const revision = Math.max(nowMs, (current?.revision ?? 0) + 1);
    const nextIndex = {
      ...index,
      installRecords: records,
      // Drop the cached plugin projection owned by changed records so the
      // next OpenClaw scan rebuilds it from the new install path.
      plugins: withoutPluginProjections(index.plugins, changedIds),
    };
    db.prepare(`
      INSERT INTO config_machine_state (state_key, value_json, updated_at_ms)
      VALUES (?, ?, ?)
      ON CONFLICT(state_key) DO UPDATE SET
        value_json = excluded.value_json,
        updated_at_ms = excluded.updated_at_ms
    `).run(INSTALLED_PLUGIN_INDEX_STATE_KEY, JSON.stringify({ revision, index: nextIndex }), revision);

    // Earlier ClawX builds recreated the retired table after OpenClaw had
    // migrated and dropped it. OpenClaw never imports it again at this
    // schema version, so its rows are stale ClawX copies.
    if (tableExists(db, 'installed_plugin_index')) {
      db.exec('DROP TABLE installed_plugin_index;');
    }

    db.exec('COMMIT;');
    committed = true;
    return true;
  } finally {
    if (!committed) {
      db.exec('ROLLBACK;');
    }
  }
}

function mutateLegacyIndexTable(db: DatabaseSync, mutate: InstallRecordsMutation, createIfMissing: boolean): boolean {
  if (createIfMissing) {
    db.exec(INSTALLED_PLUGIN_INDEX_TABLE_SQL);
  } else if (!tableExists(db, 'installed_plugin_index')) {
    return false;
  }

  const row = db.prepare(`
    SELECT install_records_json
      FROM installed_plugin_index
     WHERE index_key = ?
  `).get(INSTALLED_PLUGIN_INDEX_KEY) as { install_records_json?: string } | undefined;
  if (!row && !createIfMissing) return false;

  const records = parseInstallRecords(row?.install_records_json) ?? {};
  if (!mutate(records)) return false;

  const now = Date.now();
  if (row) {
    db.prepare(`
      UPDATE installed_plugin_index
         SET install_records_json = ?,
             updated_at_ms = ?,
             generated_at_ms = ?
       WHERE index_key = ?
    `).run(JSON.stringify(records), now, now, INSTALLED_PLUGIN_INDEX_KEY);
  } else {
    db.prepare(`
      INSERT INTO installed_plugin_index (
        index_key, version, host_contract_version, compat_registry_version,
        migration_version, policy_hash, generated_at_ms, refresh_reason,
        install_records_json, plugins_json, diagnostics_json, warning, updated_at_ms
      ) VALUES (
        ?, 1, 'clawx-managed', 'clawx-managed',
        1, 'clawx-managed', ?, 'source-changed',
        ?, '[]', '[]', ?, ?
      )
    `).run(INSTALLED_PLUGIN_INDEX_KEY, now, JSON.stringify(records), INSTALLED_PLUGIN_INDEX_WARNING, now);
  }
  return true;
}

function mutateStateDatabase(
  sqlitePath: string,
  mutate: InstallRecordsMutation,
  createIfMissing: boolean,
): boolean {
  const db = openStateDatabase(sqlitePath);
  try {
    if (usesMachineStateIndex(db)) {
      return mutateMachineStateIndex(db, sqlitePath, mutate);
    }
    // Fresh or pre-2026.10 database: OpenClaw imports this table into
    // config_machine_state during its schema migration.
    return mutateLegacyIndexTable(db, mutate, createIfMissing);
  } finally {
    db.close();
  }
}

/**
 * Upsert trusted install records into openclaw.sqlite.
 * ClawX-authored records win over stale SQLite entries for the same plugin id.
 */
export function upsertPluginInstallRecordsIntoSqlite(
  records: Record<string, Record<string, unknown>>,
): boolean {
  if (Object.keys(records).length === 0) {
    return false;
  }

  ensureOpenClawStateDirExists();
  const sqlitePath = resolveOpenClawStateSqlitePath();
  mkdirSync(join(resolveOpenClawStateDir(), 'state'), { recursive: true });

  try {
    const changed = mutateStateDatabase(sqlitePath, upsertMutation(records), true);
    if (changed) {
      logger.info(`[plugin] Persisted trusted install metadata to SQLite for: ${Object.keys(records).join(', ')}`);
    }
    return changed;
  } catch (error) {
    logger.warn('[plugin] Failed to persist trusted install metadata to SQLite:', error);
    return false;
  }
}

/**
 * Remove install records that must remain ClawX-managed rather than updated
 * from their raw upstream npm package. Also clean the legacy root-level DB
 * previously written by ClawX before OpenClaw 2026.7.1 moved state to state/.
 */
export function removePluginInstallRecordsFromSqlite(pluginIds: string[]): boolean {
  if (pluginIds.length === 0) return false;

  const stateDir = resolveOpenClawStateDir();
  const sqlitePaths = [
    resolveOpenClawStateSqlitePath(),
    join(stateDir, 'openclaw.sqlite'),
  ];
  let changed = false;

  for (const sqlitePath of sqlitePaths) {
    if (!existsSync(sqlitePath)) continue;
    try {
      if (mutateStateDatabase(sqlitePath, removeMutation(pluginIds), false)) {
        changed = true;
      }
    } catch (error) {
      logger.warn(`[plugin] Failed to remove install metadata from ${sqlitePath}:`, error);
    }
  }

  if (changed) {
    logger.info(`[plugin] Removed managed install metadata from SQLite for: ${pluginIds.join(', ')}`);
  }
  return changed;
}

/** Ensure ~/.openclaw exists before first config write in fresh installs. */
export function ensureOpenClawStateDirExists(): void {
  const stateDir = resolveOpenClawStateDir();
  if (!existsSync(stateDir)) {
    mkdirSync(stateDir, { recursive: true });
  }
}
